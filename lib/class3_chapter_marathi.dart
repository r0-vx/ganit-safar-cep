// Editorial classroom wording for Class 3. Keep all original question models,
// English text, identities, answer order and Marathi drafts for comparison.
// These local edits have not been certified by an external Marathi reviewer.
ChapterQuestion _class3Question(
  SchoolChapter chapter,
  int index,
  ChapterQuestion original,
) {
  if (chapter.grade != 3) return original;
  final i = index % 10;
  String n(Object value) => marathiDigits(value);
  late String prompt, explanation, hint;
  String? englishHint;
  switch (chapter.number) {
    case 1:
      const objects = [
        'तीन बाजू असलेली पाटी',
        'चारही बाजू समान असलेली फरशी',
        'पुस्तकाचे मुखपृष्ठ',
        'गोल ताट',
        'अंडाकृती आरसा',
        'छपरावरील त्रिकोणी पाटी',
        'चारही बाजू समान असलेली खिडकी',
        'वर्गाचा आयताकृती दरवाजा',
        'सायकलच्या चाकाची बाह्यरेषा',
        'अंड्याच्या आकाराचे चित्र',
      ];
      const explanations = [
        'त्रिकोणाला तीन सरळ बाजू असतात.',
        'चौरसाच्या चारही बाजू समान असतात आणि चारही कोपरे काटकोनाचे असतात.',
        'आयताला चार बाजू असतात. त्याच्या समोरासमोरच्या बाजू समान असतात.',
        'वर्तुळाची कड पूर्ण गोल असते. त्याला सरळ बाजू नसतात.',
        'अंडाकृती आकार लांबट गोल असतो. त्याला सरळ बाजू नसतात.',
      ];
      prompt =
          'घराच्या आसपास ${objects[i]} पाहा. या वस्तूची बाह्यरेषा कोणत्या सपाट आकारासारखी दिसते?';
      explanation = explanations[i % 5];
      hint =
          'बाह्यरेषेवरून बोट फिरवून पाहा. सरळ बाजू आणि कोपरे मोज. कड वक्र असेल तर तिचा आकारही पाहा.';
    case 2:
      final hundreds = 2 + i % 8, tens = i * 3 % 10, ones = i * 7 % 10;
      final answer = hundreds * 100 + tens * 10 + ones;
      prompt =
          '${n(hundreds)} शतके, ${n(tens)} दशके आणि ${n(ones)} एकके मिळून कोणती संख्या तयार होते?';
      explanation =
          '${n(hundreds)} शतके + ${n(tens)} दशके + ${n(ones)} एकके = ${n(answer)}. शतक, दशक आणि एकक यांच्या घरांत अंक लिहिल्यावर ही संख्या मिळते.';
      hint =
          'डावीकडून शतक, दशक आणि एकक अशी घरे लिही. प्रत्येक घरात दिलेला अंक ठेव. एखाद्या घरात काहीच नसेल तर तिथे ० लिही.';
    case 3:
      final a = 236 + i * 31, b = 112 + i * 17;
      const nouns = [
        'पाने',
        'आंबे',
        'गोट्या',
        'फुले',
        'शिंपले',
        'बिया',
        'बटणे',
        'पतंग',
        'पुस्तके',
        'पेरू',
      ];
      const collected = [
        'केली',
        'केले',
        'केल्या',
        'केली',
        'केले',
        'केल्या',
        'केली',
        'केले',
        'केली',
        'केले',
      ];
      prompt =
          'वर्गातील मुलांनी ${n(a)} ${nouns[i]} गोळा ${collected[i]}. मग आणखी ${n(b)} ${nouns[i]} गोळा ${collected[i]}. आता एकूण किती ${nouns[i]} आहेत?';
      explanation =
          '${n(a)} + ${n(b)} = ${n(a + b)}. दोन्ही गट मिळवल्यावर एकूण ${n(a + b)} ${nouns[i]} होतात.';
      hint =
          'आधीचा गट आणि नंतरचा गट एकत्र करायचा आहे, म्हणून बेरीज कर. एककाखाली एकक, दशकाखाली दशक आणि शतकाखाली शतक लिही.';
    case 4:
      final denominator = [2, 4, 4, 3, 4][i % 5];
      final numerator = [1, 1, 3, 2, 1][i % 5];
      const genitives = [
        'कागदी पोळीचे',
        'फळांच्या वडीचे',
        'बागेतील एका भागाचे',
        'रांगोळीच्या फरशीचे',
        'वाटणीच्या ताटाचे',
        'कागदी पतंगाचे',
        'चौकोनी सँडविचचे',
        'फुलांच्या वाफ्याचे',
        'रंगवलेल्या भिंतीवरील भागाचे',
        'बागेतील झेंड्याचे',
      ];
      final shaded = numerator == 1
          ? '१ भाग रंगवला आहे'
          : '${n(numerator)} भाग रंगवले आहेत';
      prompt =
          '${genitives[i]} ${n(denominator)} समान भाग केले आहेत. त्यांपैकी $shaded. रंगवलेला भाग कोणत्या अपूर्णांकाने दाखवता येईल?';
      explanation =
          'रंगवलेल्या भागांची संख्या ${n(numerator)}, म्हणून अंश ${n(numerator)}. एकूण समान भाग ${n(denominator)}, म्हणून छेद ${n(denominator)}. अपूर्णांक ${n(numerator)}/${n(denominator)} आहे.';
      hint =
          'वरच्या जागी रंगवलेल्या भागांची संख्या लिही. खालच्या जागी पूर्ण आकारातील सर्व समान भागांची संख्या लिही.';
    case 5:
      const measures = [
        'बोटाची लांबी',
        'तांदळाच्या एका दाण्याचे वजन',
        'वर्गाची लांबी',
        'शाळेच्या दप्तराचे वजन',
        'दोन गावांमधील अंतर',
        'वहीची रुंदी',
        'तांदळाच्या पोत्याचे वजन',
        'वर्गाच्या भिंतीची लांबी',
        'एका घेवड्याच्या बीचे वजन',
        'गावातून शहरापर्यंतच्या रस्त्याचे अंतर',
      ];
      final unit = _class3Option(original.options[original.correctIndex].en);
      prompt = '${measures[i]} मोजण्यासाठी कोणते एकक योग्य आहे?';
      explanation = '${measures[i]} मोजण्यासाठी $unit हे एकक वापरूया.';
      // Unlike the old shared hint, distinguish lengths from weights.
      hint = const [1, 3, 6, 8].contains(i)
          ? 'इथे वजन मोजायचे आहे. वस्तू हलकी आहे की जड, ते पाहून ग्राम किंवा किलोग्रॅम निवड.'
          : 'इथे लांबी किंवा अंतर मोजायचे आहे. लहान वस्तूसाठी सेंटीमीटर, खोलीसाठी मीटर आणि दूरच्या ठिकाणांसाठी किलोमीटर यांचा विचार कर.';
      if (const [0, 2, 4, 5, 7, 9].contains(i) &&
          original.hint.en ==
              'Choose the unit that measures mass at this scale.') {
        englishHint = 'Choose the unit that measures length at this scale.';
      }
    case 6:
      final symbols = 2 + i;
      prompt =
          'वर्गाच्या चित्रालेखात लाल पतंगांसाठी सूर्याची ${n(symbols)} चिन्हे दाखवली आहेत. सूर्याचे प्रत्येक चिन्ह १ पतंग दाखवते. लाल पतंग एकूण किती आहेत?';
      explanation =
          '${n(symbols)} × १ = ${n(symbols)}. प्रत्येक चिन्ह १ लाल पतंग दाखवते, म्हणून एकूण ${n(symbols)} लाल पतंग आहेत.';
      hint =
          'चित्रालेखातील एक चिन्ह किती वस्तू दाखवते ते आधी वाच. मग चिन्हांची संख्या आणि एका चिन्हासाठी दिलेली संख्या गुणा.';
    case 7:
      final row = ['A', 'B', 'C'][i % 3], column = 1 + i % 4;
      const places = ['वाचनालय', 'विहीर', 'बाग', 'शाळा', 'पूल'];
      prompt =
          'मीराच्या नकाशात ${places[i % 5]} हे ठिकाण $row ओळीत आणि ${n(column)} स्तंभात आहे. जाळीतील या ठिकाणाचा पत्ता कोणता?';
      explanation =
          'आधी ओळीचे अक्षर $row आणि मग स्तंभाचा अंक ${n(column)} वाच. म्हणून जाळीतील पत्ता $row${n(column)} आहे.';
      hint =
          'ओळीचे अक्षर आणि स्तंभाचा अंक शोध. ती ओळ आणि तो स्तंभ जिथे भेटतात, तिथे ठिकाण आहे.';
    case 8:
      final rows = 12 + i * 4, each = 2 + i % 5;
      prompt =
          'बागेत रोपांच्या ${n(rows)} ओळी आहेत. प्रत्येक ओळीत ${n(each)} रोपे आहेत. बागेत एकूण किती रोपे आहेत?';
      explanation =
          'प्रत्येक ओळीत ${n(each)} रोपे आहेत आणि अशा ${n(rows)} ओळी आहेत. ${n(rows)} × ${n(each)} = ${n(rows * each)}. एकूण ${n(rows * each)} रोपे आहेत.';
      hint =
          'सर्व ओळींत सारखीच रोपे आहेत. एकूण रोपे शोधण्यासाठी ओळींची संख्या आणि एका ओळीतील रोपांची संख्या गुणा.';
    case 9:
      final groups = 2 + i % 4, each = 3 + i % 6, remainder = i % groups;
      final total = groups * each + remainder;
      final leftover = remainder == 0
          ? 'काहीही उरत नाही'
          : remainder == 1
          ? '१ उरते'
          : '${n(remainder)} उरतात';
      if (i.isOdd) {
        prompt =
            '${n(total)} जांभळे ${n(groups)} वाट्यांत समान वाटायची आहेत. प्रत्येक वाटीत शक्य तितकी सारखी जांभळे ठेवल्यावर किती जांभळे उरतील?';
        explanation =
            '${n(total)} = ${n(groups)} × ${n(each)}${remainder == 0 ? '' : ' + ${n(remainder)}'}. प्रत्येक वाटीत ${n(each)} जांभळे ठेवता येतात आणि $leftover. म्हणून बाकी ${n(remainder)} आहे.';
      } else {
        prompt =
            'चित्रांची ${n(total)} कार्डे ${n(groups)} मित्रांना समान वाटायची आहेत. प्रत्येक मित्राला जास्तीत जास्त किती कार्डे मिळतील?';
        explanation =
            '${n(total)} = ${n(groups)} × ${n(each)}${remainder == 0 ? '' : ' + ${n(remainder)}'}. प्रत्येक मित्राला ${n(each)} कार्डे मिळतील${remainder == 0 ? '.' : ' आणि $leftover.'}';
      }
      hint =
          'प्रत्येक गटाला एकेक वस्तू देत समान वाटणी कर. सर्वांना सारख्या वस्तू मिळाल्या पाहिजेत. आणखी एक फेरी पूर्ण करता येत नसेल तर उरलेल्या वस्तू म्हणजे बाकी.';
    case 10:
      const scenes = [
        'वहीच्या कोपऱ्यातील कोन',
        'कात्री थोडी उघडल्यावर तयार झालेला कोन',
        'गोठ्याचा दरवाजा रुंद उघडल्यावर तयार झालेला कोन',
        'चौकोनी फरशीच्या कोपऱ्यातील कोन',
        'कागदी त्रिकोणाच्या टोकाचा कोन',
        'चौकोनी खिडकीच्या चौकटीतील कोन',
        'दोन अरुंद वाटा जिथे मिळतात तिथला कोन',
        'पाव वळणापेक्षा जास्त उघडलेल्या फाटकाचा कोन',
        'चौकोनी फोटोच्या चौकटीतील कोन',
        'कागदी पंख्याच्या अरुंद टोकाचा कोन',
      ];
      final answer = _class3Option(original.options[original.correctIndex].en);
      prompt =
          '${scenes[i]} पाहा. हा कोन कागदाच्या चौकोनी कोपऱ्यापेक्षा लहान, तेवढाच की मोठा आहे?';
      explanation =
          'कागदाच्या चौकोनी कोपऱ्याला काटकोन म्हणतात. ${scenes[i]} $answer आहे.';
      hint =
          'कागदाचा चौकोनी कोपरा या कोनावर ठेवला आहे, अशी कल्पना कर. कोन कमी उघडला आहे, तेवढाच उघडला आहे की जास्त उघडला आहे, ते पाहा.';
    case 11:
      const objects = [
        'फुलपाखराचे चित्र',
        'मातीच्या बेढब आकाराचे चित्र',
        'घडीच्या कागदातून कापलेला हृदयाचा आकार',
        'वाकडी मधली शीर असलेल्या अनियमित पानाचे चित्र',
        'डोळ्यांसाठी सारखी भोके असलेला मुखवटा',
        'मधल्या सरळ रेषेवर घडी घालून कापलेले कागदी पान',
        'कागदातून कापलेला अनियमित ढगाचा आकार',
        'दोन्ही बाजूंना सारखी नक्षी असलेली चौरस फरशी',
        'पुठ्ठ्यातून कापलेला एका बाजूचा बाण',
        'मध्यातून घडी घातलेला पाच टोकांचा कागदी तारा',
      ];
      final matches = [
        true,
        false,
        true,
        false,
        true,
        true,
        false,
        true,
        false,
        true,
      ][i];
      prompt =
          '${objects[i]} पाहा. मधल्या रेषेवर कागदाला घडी घातली, तर दोन्ही अर्धे भाग एकमेकांवर तंतोतंत जुळतील का?';
      explanation = matches
          ? 'या चित्राचे दोन्ही अर्धे भाग घडीच्या रेषेवर तंतोतंत जुळतात.'
          : 'या चित्राचे दोन्ही अर्धे भाग घडीच्या रेषेवर तंतोतंत जुळत नाहीत.';
      hint =
          'दाखवलेल्या मधल्या रेषेवर कागद दुमडल्याची कल्पना कर. एका बाजूची कड दुसऱ्या बाजूच्या कडेवर जुळते का ते पाहा. तिथे आरसा ठेवल्याचीही कल्पना करता येईल.';
    case 12:
      final litres = 1 + i;
      prompt =
          'एका जगात ${n(litres)} लिटर पाणी मावते. अर्धा लिटर पाणी मावणारे किती कप ओतल्यावर जग पूर्ण भरेल?';
      explanation =
          '१ लिटर भरण्यासाठी अर्धा लिटरचे २ कप लागतात. म्हणून ${n(litres)} लिटर भरण्यासाठी ${n(litres * 2)} कप लागतील.';
      hint =
          'अर्धा लिटरचे दोन कप मिळून एक लिटर होते. प्रत्येक लिटरसाठी असे दोन कप मोज.';
    case 13:
      final hour = 1 + i % 12, minutes = [0, 15, 30, 45][i % 4];
      final next = hour == 12 ? 1 : hour + 1;
      final longHand = minutes == 0 ? 12 : minutes ~/ 5;
      final position = minutes == 0
          ? '${n(hour)} वर आहे'
          : '${n(hour)} आणि ${n(next)} यांच्या मध्ये आहे';
      final time = '${n(hour)}:${n(minutes.toString().padLeft(2, '0'))}';
      prompt =
          'घड्याळाचा लहान काटा $position आणि मोठा काटा ${n(longHand)} वर आहे. घड्याळात किती वाजले आहेत?';
      explanation = 'घड्याळात $time वाजले आहेत.';
      hint =
          'लहान काटा तास दाखवतो. मोठा काटा मिनिटे दाखवतो. मोठ्या काट्याच्या प्रत्येक पुढच्या अंकासाठी पाच मिनिटे मोज.';
    case 14:
      final jump = 1 + i % 4, start = 2 + i * 2, third = start + 2 * jump;
      prompt =
          '${n(start)}, ${n(start + jump)}, ${n(third)}, __. या मालिकेत पुढची संख्या कोणती?';
      explanation =
          'प्रत्येक वेळी ${n(jump)} मिळवले आहेत. म्हणून ${n(third)} + ${n(jump)} = ${n(third + jump)}. पुढची संख्या ${n(third + jump)} आहे.';
      hint =
          'एका संख्येत किती मिळवल्यावर पुढची संख्या येते, ते शोध. शेवटच्या संख्येतही तेवढेच मिळव.';
    default:
      return original;
  }
  return ChapterQuestion(
    id: original.id,
    prompt: classroomWording(original.prompt, prompt, grade: 3),
    explanation: classroomWording(original.explanation, explanation, grade: 3),
    hint: classroomWording(original.hint, hint, grade: 3, english: englishHint),
    options: List<Words>.unmodifiable([
      for (final option in original.options)
        classroomWording(option, _class3Option(option.en), grade: 3),
    ]),
