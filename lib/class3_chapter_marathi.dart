  const terms = {
    'triangle': 'त्रिकोण',
    'square': 'चौरस',
    'rectangle': 'आयत',
    'circle': 'वर्तुळ',
    'oval': 'अंडाकृती',
    'centimetres': 'सेंटीमीटर',
    'metres': 'मीटर',
    'kilometres': 'किलोमीटर',
    'grams': 'ग्राम',
    'kilograms': 'किलोग्रॅम',
    'smaller than a square corner': 'काटकोनापेक्षा लहान',
    'the same as a square corner': 'काटकोनाएवढा',
    'larger than a square corner': 'काटकोनापेक्षा मोठा',
    'a curved line, not an angle': 'वक्र रेषा आहे; कोन नाही',
    'yes, the two sides match': 'हो, दोन्ही भाग जुळतात',
    'no, the two sides do not match': 'नाही, दोन्ही भाग जुळत नाहीत',
    'it has no sides': 'त्याला बाजू नाहीत',
    'it is a solid': 'तो घन आकार आहे',
    'it has four equal sides': 'त्याच्या चारही बाजू समान आहेत',
    'it is a circle': 'ते वर्तुळ आहे',
  };
  if (terms.containsKey(english)) return terms[english]!;
  if (RegExp(r'^\d+(?:[/\:]\d+)?$').hasMatch(english) ||
      RegExp(r'^[ABC][1-4]$').hasMatch(english)) {
    return marathiDigits(english);
  }
  throw StateError('Unreviewed Class 3 answer option: $english');
}

