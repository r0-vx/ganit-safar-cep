    story: classroomWording(
      original.story,
      '$intro ${first.prompt.mr}',
      grade: 2,
    ),
    concept: classroomWording(original.concept, concept, grade: 2),
    workedExample: classroomWording(
      original.workedExample,
      first.explanation.mr,
      grade: 2,
      english: chapter.number == 6 ? first.explanation.en : null,
    ),
