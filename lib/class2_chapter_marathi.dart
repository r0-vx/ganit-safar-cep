  return ChapterQuestion(
    id: original.id,
    prompt: classroomWording(original.prompt, prompt, grade: 2),
    explanation: classroomWording(
      original.explanation,
      explanation,
      grade: 2,
      english: englishExplanation,
    ),
    hint: classroomWording(original.hint, hint, grade: 2),
    options: [
      for (final option in original.options)
        _class2Option(option, ordering: chapter.number == 6),
    ],
    correctIndex: original.correctIndex,
    objects: original.objects,
    visualKind: original.visualKind,
  );
}

String _class2Sequence(String source) => RegExp(
  r'\d+',
).allMatches(source).map((m) => marathiDigits(m.group(0)!)).join(' → ');

Words _class2Option(Words original, {required bool ordering}) {
  String? english;
  final placeholder = original.en == 'Option 1' || original.en == 'Option 2';
  final marathi = ordering && !placeholder
      ? _class2Sequence(original.en)
      : _class2OptionText(original.en);
  if (ordering) english = original.en.replaceAll(RegExp(r'\s*<\s*'), ' → ');
  if (original.en == 'Option 1') english = 'None of these choices';
  if (original.en == 'Option 2') english = 'All numbers are equal';
  return classroomWording(original, marathi, grade: 2, english: english);
}

