part of 'chapter_catalogue.dart';

/// Age-appropriate Class 2 classroom wording. Every question keeps its original
/// numerical model, option positions and source identity. Original drafts stay
/// available alongside the contextual wording for later educator review.
ChapterQuestion _class2Question(
  SchoolChapter chapter,
  int index,
  ChapterQuestion original,
) {
  if (chapter.grade != 2) return original;
  final i = index % 10;
  String n(Object value) => marathiDigits(value);
  final numbers = RegExp(
    r'\d+',
  ).allMatches(original.prompt.en).map((m) => int.parse(m.group(0)!)).toList();
  final correct = original.options[original.correctIndex].en;
  var prompt = '', explanation = '', hint = '';
  String? englishExplanation;
  switch (chapter.number) {
    case 1:
      const names = [
        'फाशासारखा ठोकळा (घन)',
        'चेंडूसारखा गोल आकार (गोल)',
        'दोन्ही टोकांना सपाट गोल असलेला डब्यासारखा आकार (दंडगोल)',
        'पेटीसारखा आयताकृती ठोकळा (इष्टिकाचिती)',
        'टोकदार टोपीसारखा दिसणारा आकार (शंकू)',
        'दोन्ही टोकांना त्रिकोण असलेला लांबट आकार (त्रिकोणी प्रिझम)',
        'चौरस तळ आणि वर एक टोक असलेला आकार (चौरस पायाचा पिरॅमिड)',
        'दोन्ही टोकांना सहा बाजूंचे आकार असलेला लांबट ठोकळा (षट्कोनी प्रिझम)',
        'अर्ध्या चेंडूसारखा आकार (अर्धगोल)',
        'त्रिकोणी तळ आणि वर एक टोक असलेला आकार (त्रिकोणी पिरॅमिड)',
      ];
      final name = names[i];
      prompt =
          '$name पाहा. त्याचे बाहेरचे पृष्ठभाग कसे आहेत? योग्य वर्णन निवडा.';
      explanation = switch (i) {
        0 =>
          'फाशासारख्या घनाला ६ सपाट पृष्ठभाग असतात. प्रत्येक पृष्ठभाग चौरस आकाराचा असतो.',
        1 =>
          'चेंडूसारख्या गोलाचा बाहेरचा भाग वळलेला म्हणजे वक्र असतो. त्याला एकही सपाट पृष्ठभाग नसतो.',
        2 =>
          'डब्यासारख्या दंडगोलाला वर आणि खाली असे २ सपाट, वर्तुळाकार पृष्ठभाग असतात. भोवतीचा १ पृष्ठभाग वळलेला असतो.',
        3 =>
          'पेटीसारख्या आयताकृती ठोकळ्याला इष्टिकाचिती म्हणतात. त्याला ६ सपाट, आयताकृती पृष्ठभाग असतात.',
        4 =>
          'टोकदार टोपीसारख्या दिसणाऱ्या शंकूचा तळ सपाट आणि वर्तुळाकार असतो. त्याचा भोवतीचा १ पृष्ठभाग वळलेला असतो.',
        5 =>
          'दोन्ही टोकांना त्रिकोण असलेल्या लांबट आकाराला त्रिकोणी प्रिझम म्हणतात. त्याला २ त्रिकोणी आणि ३ आयताकृती सपाट पृष्ठभाग असतात.',
        6 =>
          'चौरस तळापासून वर एका टोकाकडे जाणारा हा पिरॅमिड आहे. तळाचा १ पृष्ठभाग चौरस आणि उरलेले ४ पृष्ठभाग त्रिकोणी असतात.',
        7 =>
          'या लांबट ठोकळ्याच्या दोन्ही टोकांना प्रत्येकी ६ बाजूंचा आकार आहे. म्हणून त्याला षट्कोनी प्रिझम म्हणतात. त्याला २ षट्कोनी आणि ६ आयताकृती सपाट पृष्ठभाग असतात.',
        8 =>
          'अर्ध्या चेंडूसारख्या अर्धगोलाला १ सपाट, वर्तुळाकार पृष्ठभाग असतो. उरलेला १ पृष्ठभाग वळलेला असतो.',
        _ =>
          'त्रिकोणी तळापासून वर एका टोकाकडे जाणाऱ्या पिरॅमिडचे चारही पृष्ठभाग त्रिकोणी असतात.',
      };
      hint =
          'वस्तूच्या बाहेरच्या बाजूंना पृष्ठभाग म्हणतात. त्यांतील सपाट भाग आणि वळलेला भाग वेगवेगळे पाहा.';
    case 2:
      final tens = numbers[0], ones = numbers[1];
      prompt =
          '${n(tens)} दशक आणि ${n(ones)} एकक मिळून कोणती संख्या तयार होते?';
      explanation =
          '${n(tens)} दशक म्हणजे ${n(tens * 10)}. त्यात ${n(ones)} एकक मिळवा: ${n(tens * 10)} + ${n(ones)} = ${n(correct)}.';
      hint =
          'आधी दशकाच्या स्थानी असलेला अंक लिहा. त्याच्या उजवीकडे एककाचा अंक लिहा.';
    case 3:
      final ones = numbers[1];
      final loose = ones == 1
          ? '१ सुटी वस्तू आहे'
          : '${n(ones)} सुट्या वस्तू आहेत';
      prompt = 'दहाच्या १ गटासोबत $loose. एकूण किती वस्तू आहेत?';
      explanation =
          '१ दशक म्हणजे १० वस्तू. त्यात ${n(ones)} एकक मिळवल्यावर १० + ${n(ones)} = ${n(correct)} वस्तू होतात.';
      hint = 'दहाचा पूर्ण गट आधी घ्या. त्यानंतर सुट्या वस्तू मोजा.';
    case 4:
    case 13:
    case 17:
      final step = numbers[1] - numbers[0];
      prompt =
          'ही संख्यामाला पाहा: ${n(numbers[0])}, ${n(numbers[1])}, ${n(numbers[2])}, __. पुढची संख्या कोणती येईल?';
      explanation =
          'प्रत्येक वेळी ${n(step)} मिळवले आहेत. म्हणून ${n(numbers[2])} + ${n(step)} = ${n(correct)} ही पुढची संख्या आहे.';
      hint =
          'पहिल्या संख्येपासून दुसरीपर्यंत किती वाढले ते पाहा. पुढेही तेवढीच वाढ होते का ते तपासा.';
    case 5:
      final a = numbers[0], b = numbers[1];
      prompt =
          '${n(a)} __ ${n(b)} या दोन संख्यांमध्ये कोणते चिन्ह येईल: <, > की =?';
      final relation = a < b
          ? 'लहान'
          : a > b
          ? 'मोठी'
          : 'समान';
      explanation = a == b
          ? 'दोन्ही संख्या समान आहेत. म्हणून ${n(a)} = ${n(b)} असे लिहितो.'
          : '${n(a)} ही संख्या ${n(b)} पेक्षा $relation आहे. म्हणून ${n(a)} $correct ${n(b)} असे लिहितो.';
      hint = 'आधी दोन्ही संख्यांची दशके पाहा. दशके सारखी असतील, तर एकके पाहा.';
    case 6:
      final descending = original.prompt.en.contains('greatest to least');
      final sequence = _class2Sequence(correct);
      prompt =
          '${numbers.take(3).map(n).join(', ')} या संख्या ${descending ? 'मोठ्यापासून लहानाकडे' : 'लहानापासून मोठ्याकडे'} क्रमाने लावा.';
      explanation =
          '${descending ? 'सर्वांत मोठी संख्या आधी घ्या. मग तिच्यापेक्षा लहान संख्या लावा.' : 'सर्वांत लहान संख्या आधी घ्या. मग तिच्यापेक्षा मोठी संख्या लावा.'} योग्य क्रम: $sequence.';
      hint = descending
          ? 'सर्वांत मोठी संख्या शोधा. ती आधी ठेवा आणि उरलेल्या दोन संख्यांचा क्रम ठरवा.'
          : 'सर्वांत लहान संख्या शोधा. ती आधी ठेवा आणि उरलेल्या दोन संख्यांचा क्रम ठरवा.';
      englishExplanation = original.explanation.en.replaceAll(
        RegExp(r'\s*<\s*'),
        ' → ',
      );
    case 7:
      final step = numbers[1] - numbers[0];
      prompt =
          '${numbers.take(3).map(n).join(', ')}, __. त्याच टप्प्याने पुढे मोजल्यावर कोणती संख्या येईल?';
      explanation =
          'प्रत्येक टप्प्यात ${n(step)} मिळवले आहेत. पुढच्या टप्प्यासाठी ${n(numbers[2])} + ${n(step)} = ${n(correct)} करा.';
      hint =
          'एका संख्येपासून पुढच्या संख्येपर्यंत किती वाढते ते शोधा. पुढेही तेवढेच मिळवा.';
    case 8:
    case 14:
      final a = numbers[0], b = numbers[1];
      const nouns = [
        'पाने',
        'आंबे',
        'गोट्या',
        'फुले',
        'शिंपले',
        'बिया',
        'बटणे',
        'पतंग',
        'पुस्तके',
        'पेरू',
      ];
      const collected = [
        'केली',
        'केले',
        'केल्या',
        'केली',
        'केले',
        'केल्या',
        'केली',
        'केले',
        'केली',
        'केले',
      ];
      const received = [
        'मिळाली',
        'मिळाले',
        'मिळाल्या',
        'मिळाली',
        'मिळाले',
        'मिळाल्या',
        'मिळाली',
        'मिळाले',
        'मिळाली',
        'मिळाले',
      ];
      prompt =
          'वर्गातील मुलांनी ${n(a)} ${nouns[i]} गोळा ${collected[i]}. नंतर आणखी ${n(b)} ${nouns[i]} ${received[i]}. आता एकूण किती ${nouns[i]} आहेत?';
      if (chapter.number == 14) {
        final ones = a % 10 + b % 10;
        explanation = ones >= 10
            ? 'आधी एकके मिळवा: ${n(a % 10)} + ${n(b % 10)} = ${n(ones)}. त्यांतील १० एककांचा १ दशक करा आणि तो दशकांच्या बेरजेत मिळवा. ${n(a)} + ${n(b)} = ${n(correct)}.'
            : 'आधी एकके मिळवा: ${n(a % 10)} + ${n(b % 10)} = ${n(ones)}. ही बेरीज १० पेक्षा कमी असल्याने नवीन दशक करायची गरज नाही. आता दशकांची बेरीज करा. ${n(a)} + ${n(b)} = ${n(correct)}.';
        if (ones < 10)
          englishExplanation =
              'Ones: ${a % 10} + ${b % 10} = $ones. No regrouping is needed because the ones total is less than ten: $a + $b = $correct.';
        hint =
            'एककांची बेरीज आधी करा. ती १० किंवा जास्त झाली, तरच १० एककांचा १ दशक करा.';
      } else {
        explanation =
            'दोन्ही गटांतील ${nouns[i]} एकत्र केल्यावर बेरीज होते: ${n(a)} + ${n(b)} = ${n(correct)}.';
        hint =
            'दोन्ही गट एकत्र करा. पहिल्या गटाच्या संख्येत दुसऱ्या गटाची संख्या मिळवा.';
      }
    case 9:
    case 15:
      final a = numbers[0], b = numbers[1];
      const nouns = ['शेंगा', 'आंबे', 'शिंपले', 'चित्रांची कार्डे', 'बटणे'];
      const used = ['वापरल्या', 'वापरले', 'वापरले', 'वापरली', 'वापरली'];
      const remaining = ['उरल्या', 'उरले', 'उरले', 'उरली', 'उरली'];
      prompt =
          '${n(a)} ${nouns[i % 5]} आहेत. त्यांपैकी ${n(b)} ${nouns[i % 5]} ${used[i % 5]}. आता किती ${nouns[i % 5]} ${remaining[i % 5]} आहेत?';
      if (chapter.number == 15) {
        final tens = a ~/ 10 - 1, removeOnes = b % 10;
        explanation =
            '${n(a)} मध्ये १ दशक मोकळा केला, की ${n(tens)} दशक आणि १२ एकक मिळतात. १२ एककांतून ${n(removeOnes)} एकक वजा करा. नंतर दशकांची वजाबाकी करा: ${n(a)} − ${n(b)} = ${n(correct)}.';
        hint =
            'एककांतून वजा करायला एकक कमी पडले, तर १ दशक मोकळा करून १० एकक घ्या.';
      } else {
        explanation =
            'वापरलेल्या वस्तू सुरुवातीच्या गटातून कमी करा: ${n(a)} − ${n(b)} = ${n(correct)}.';
        hint =
            'सुरुवातीची संख्या लक्षात ठेवा. वापरलेल्या वस्तूंच्या संख्येइतके मागे मोजा.';
      }
    case 10:
      final a = numbers[0], total = numbers[1];
      prompt =
          '${n(a)} + __ = ${n(total)} या बेरजेत रिकाम्या जागी कोणती संख्या येईल?';
      explanation =
          'एकूण ${n(total)} मधून माहीत असलेली ${n(a)} ही संख्या वजा करा: ${n(total)} − ${n(a)} = ${n(correct)}. तपासून पाहा: ${n(a)} + ${n(correct)} = ${n(total)}.';
      hint =
          'एकूण संख्येतून दिलेली संख्या वजा केली, की रिकाम्या जागेतील संख्या मिळेल.';
    case 11:
    case 20:
      final rows = numbers[0], perRow = numbers[1];
      prompt =
          'बागेत ${n(rows)} ओळी आहेत. प्रत्येक ओळीत ${n(perRow)} रोपे आहेत. सर्व ओळींत मिळून किती रोपे आहेत?';
      explanation =
          'प्रत्येक ओळीत ${n(perRow)} रोपे आहेत. म्हणून ${List.filled(rows, n(perRow)).join(' + ')} = ${n(correct)}. हेच ${n(rows)} × ${n(perRow)} = ${n(correct)} असे लिहितो.';
      hint =
          'एका ओळीतील रोपे मोजा. प्रत्येक ओळीत तेवढीच रोपे आहेत. तेवढी संख्या प्रत्येक ओळीसाठी मिळवा.';
    case 12:
      const scenes = [
        'रंगीत खडूची लांबी',
        'कलिंगडाचे वजन',
        'बाटलीतील पाण्याचे प्रमाण',
        'दोन गावांमधले अंतर',
        'कागदाच्या एका क्लिपचे वजन',
        'वहीची रुंदी',
        'तांदळाच्या पोत्याचे वजन',
        'वर्गाच्या भिंतीची लांबी',
        'एका कडधान्याच्या दाण्याचे वजन',
        'गावापासून शहरापर्यंतचे अंतर',
      ];
      final scene = scenes[i];
      final unit = _class2OptionText(correct);
      prompt = '$scene मोजण्यासाठी कोणते एकक योग्य ठरेल?';
      explanation = '$scene मोजण्यासाठी $unit हे एकक वापरतो.';
      hint =
          'लांबी किंवा अंतर मोजायचे आहे, वजन मोजायचे आहे की पाणी किती आहे ते मोजायचे आहे, हे आधी पाहा. मग योग्य एकक निवडा.';
    case 16:
      final symbols = numbers[0], scale = numbers[1];
      prompt =
          'वर्गाच्या चित्र-तक्त्यात लाल पतंगांसाठी सूर्याच्या ${n(symbols)} खुणा आहेत. प्रत्येक खूण म्हणजे ${n(scale)} पतंग. लाल पतंग एकूण किती आहेत?';
      explanation =
          'एका सूर्याच्या खुणेने ${n(scale)} पतंग दाखवला आहे. ${n(symbols)} खुणांसाठी ${n(symbols)} × ${n(scale)} = ${n(correct)} लाल पतंग होतात.';
      hint =
          'तक्त्याची खूण आधी समजून घ्या. १ चित्र किती वस्तू दाखवते ते पाहून मोजा.';
    case 18:
      final weeks = numbers[0];
      prompt =
          'दिनदर्शिकेत ${n(weeks)} पूर्ण ${weeks == 1 ? 'आठवडा दाखवला आहे' : 'आठवडे दाखवले आहेत'}. त्यात एकूण किती दिवस आहेत?';
      explanation =
          '१ आठवड्यात ७ दिवस असतात. म्हणून ${n(weeks)} × ७ = ${n(correct)} दिवस होतात.';
      hint =
          'प्रत्येक आठवड्यासाठी ७ दिवस मोजा. ७ ही संख्या तितक्या वेळा मिळवा.';
    case 19:
      final price = numbers[0], count = numbers[1];
      prompt =
          'मेळाव्यात एका कागदी फिरकीची किंमत ₹${n(price)} आहे. अशा ${n(count)} ${count == 1 ? 'फिरकीसाठी' : 'फिरक्यांसाठी'} किती रुपये द्यावे लागतील?';
      explanation =
          'प्रत्येक फिरकीसाठी ₹${n(price)} द्यायचे आहेत. म्हणून ${n(count)} × ₹${n(price)} = ₹${n(correct)} ही एकूण किंमत होते.';
      hint =
