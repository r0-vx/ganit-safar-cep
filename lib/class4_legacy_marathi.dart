/// A Class 4-only classroom rewrite of the original topic tools. The numerical
/// model and English source are retained; wording is composed from the actual
/// quantities and interaction, rather than replacements inside old sentences.
Question _class4LegacyQuestion(Question q) {
  if (q.metadata?.grade != 4) return q;
  final topic = q.metadata!.topic;
  final a = class4Digits(q.a), b = class4Digits(q.b);
  final answer = class4Digits(q.answer);
  var prompt = q.prompt.mr, explanation = q.explanation.mr;
  switch (topic) {
    case 'count':
      prompt = 'चित्रातील सफरचंदे एकेक करून मोजा. एकूण किती सफरचंदे आहेत?';
      explanation = q.a == 1
          ? 'प्रत्येक सफरचंदाला एकदाच स्पर्श करून मोजा. चित्रात १ सफरचंद आहे.'
          : 'प्रत्येक सफरचंदाला एकदाच स्पर्श करून मोजा. चित्रात एकूण $a सफरचंदे आहेत.';
    case 'place':
      // The legacy template asks for complete groups of ten (a ~/ 10), which
      // differs from the digit in the tens position when the number exceeds 99.
      prompt =
          '$a वस्तूंचे दहा-दहाचे गट केले, तर असे किती पूर्ण गट तयार होतील?';
      explanation =
          'दहा एककांचा गट म्हणजे एक दशक. $a = $answer × १० + ${class4Digits(q.a % 10)}. म्हणजे दहाचे $answer पूर्ण गट आणि ${class4Digits(q.a % 10)} एकक उरतात.';
    case 'add':
      final first = q.a == 1 ? '$a आंबा आहे' : '$a आंबे आहेत';
      final more = q.b == 1 ? '$b आंबा' : '$b आंबे';
      prompt =
          'मीराकडे $first. तिची मैत्रीण तिला आणखी $more देते. आता मीराकडे एकूण किती आंबे आहेत?';
      explanation =
          'आणखी आंबे मिळाले, म्हणून दोन्ही गटांतील आंब्यांच्या संख्यांची बेरीज करा. $a + $b = $answer. आता एकूण $answer आंबे आहेत.';
    case 'subtract':
      final start = q.a == 1 ? '$a केळे आहे' : '$a केळी आहेत';
      final eaten = q.b == 1 ? '$b केळे खाल्ले' : '$b केळी खाल्ली';
      prompt = '$start. त्यातील आपण $eaten. आता किती केळी उरली?';
      final remainder = q.answer == 0
          ? 'आता एकही केळे उरलेले नाही.'
          : q.answer == 1
          ? 'आता १ केळे उरले आहे.'
          : 'आता $answer केळी उरली आहेत.';
      explanation =
          '$a पासून $b वेळा एक-एक संख्या मागे मोजा. $a − $b = $answer. $remainder';
    case 'multiply':
      final perGroup = q.b == 1 ? '$b फूल आहे' : '$b फुले आहेत';
      prompt =
          'फुलांचे $a समान गट आहेत. प्रत्येक गटात $perGroup. सर्व गटांत मिळून किती फुले आहेत?';
      explanation =
          'प्रत्येक गटात $perGroup. सर्व गटांतील फुलांची बेरीज करा: ${List.filled(q.a, b).join(' + ')} = $answer. हेच गणित गुणाकाराने $a × $b = $answer असे लिहितो.';
    case 'divide':
      final books = q.a == 1 ? '$a पुस्तक' : '$a पुस्तके';
      final children = q.b == 1
          ? (q.a == 1 ? 'एका मुलाला द्यायचे आहे' : 'एका मुलाला द्यायची आहेत')
          : '$b मुलांमध्ये सारखी वाटायची आहेत';
      prompt = '$books $children. प्रत्येक मुलाला किती पुस्तके मिळतील?';
      final share = q.answer == 1 ? '१ पुस्तक मिळते' : '$answer पुस्तके मिळतात';
      explanation =
          'समान वाटणी केल्यावर प्रत्येक मुलाला $share. तपासून पाहा: $b × $answer = $a. म्हणून $a ÷ $b = $answer.';
    case 'fraction':
      prompt =
          'पिझ्झाचे $b सारख्या आकाराचे भाग केले आहेत. त्यांपैकी $a भाग रंगवा. किती भाग रंगवले?';
      final coloured = q.a == 1 ? '१ भाग रंगवला आहे' : '$a भाग रंगवले आहेत';
      explanation =
          'पूर्ण पिझ्झाचे $b समान भाग आहेत आणि त्यांपैकी $coloured. आपण हा रंगवलेला भाग $a/$b असा दाखवतो. सर्व भाग सारख्या आकाराचे असणे आवश्यक आहे.';
    case 'shape':
      final seed = q.metadata!.seed;
      final scene = const [
        'मीराने एक आकार काढला आहे.',
        'रवीला एका आकाराचे खेळणे सापडले आहे.',
        'वर्गातील चित्रात एक आकार दिसतो.',
        'शेतकऱ्याने वाळूत एक आकार काढला आहे.',
        'मैत्रिणीने कागदाचा एक आकार बनवला आहे.',
      ][seed ~/ 3 % 5];
      final shape = const ['त्रिकोणाला', 'चौरसाला', 'वर्तुळाला'][q.a];
      prompt = '$scene या $shape किती सरळ बाजू आहेत?';
      explanation = switch (q.a) {
        0 => 'त्रिकोणाला ३ सरळ बाजू असतात. प्रत्येक बाजू एकदाच मोजा.',
        1 => 'चौरसाला ४ सरळ बाजू असतात. प्रत्येक बाजू एकदाच मोजा.',
        _ =>
          'वर्तुळाची कडा वक्र असते. त्याला सरळ बाजू किंवा कोपरे नसतात. म्हणून सरळ बाजूंची संख्या ० आहे.',
      };
    case 'measure':
      prompt =
          'पेन्सिलचे एक टोक पट्टीवरील ० च्या रेषेवर ठेवले आहे. दुसरे टोक $a सेमीच्या रेषेवर येते. पेन्सिलची लांबी किती आहे?';
      explanation =
          'लांबी मोजताना पट्टीवरील ० पासून सुरुवात करा. पेन्सिल ० पासून $a सेमीपर्यंत आहे, म्हणून तिची लांबी $a सेमी आहे.';
    case 'time':
      prompt =
          'घड्याळाचा मिनिटकाटा १२ वर आहे. तासकाटा पाहून सांगा: किती वाजले आहेत?';
      final time = q.a == 1 ? '१ वाजला आहे' : '$a वाजले आहेत';
      explanation =
          'लहान तासकाटा $a या अंकाकडे दाखवतो आणि मोठा मिनिटकाटा १२ वर आहे. म्हणून $time.';
    case 'money':
      prompt =
          'तुमच्याकडे ₹$a आणि ₹$b अशा दोन रकमा आहेत. दोन्ही मिळून किती रुपये होतात?';
      explanation =
          'दोन्ही रकमांची बेरीज करा: ₹$a + ₹$b = ₹$answer. एकूण रक्कम $answer रुपये आहे.';
    case 'pattern':
      prompt =
          'ही संख्यामाला पाहा: $a, ${class4Digits(q.a + q.b)}, ${class4Digits(q.a + 2 * q.b)}, … पुढची संख्या कोणती येईल?';
      explanation =
          'प्रत्येक पुढची संख्या आधीच्या संख्येपेक्षा $b ने मोठी आहे. ${class4Digits(q.a + 2 * q.b)} मध्ये $b मिळवल्यावर $answer मिळते. म्हणून पुढची संख्या $answer आहे.';
    case 'data':
      final goats = q.b == 1 ? '१ शेळी आहे' : '$b शेळ्या आहेत';
      prompt =
          'शेतावर $a गायी आहेत आणि $goats. दोन्ही मिळून एकूण किती प्राणी आहेत?';
      explanation =
          'गायींच्या स्तंभातून $a आणि शेळ्यांच्या स्तंभातून $b ही संख्या वाचा. दोन्ही संख्या मिळवा: $a + $b = $answer. शेतावर एकूण $answer प्राणी आहेत.';
    case 'word':
      final first = q.a == 1 ? '१ मूल आहे' : '$a मुले आहेत';
      final joining = q.b == 1 ? '१ मूल चढते' : '$b मुले चढतात';
      prompt =
          'आगगाडीत $first. गावाच्या स्थानकावर आणखी $joining. आता आगगाडीत एकूण किती मुले आहेत?';
      explanation =
          'आणखी मुले आगगाडीत चढली, त्यामुळे मुलांची संख्या वाढली. म्हणून बेरीज करा: $a + $b = $answer. आता आगगाडीत $answer मुले आहेत.';
  }
  // These interaction prompts intentionally replace the topic story in the
  // existing English generator. Apply the corresponding complete Marathi task.
  switch (q.type) {
    case 'order':
      final sorted = List<int>.from(q.options)..sort();
      prompt =
          'दिलेल्या संख्या सर्वांत लहान संख्येपासून सर्वांत मोठ्या संख्येपर्यंत क्रमाने लावा.';
      explanation =
          'आधी सर्वांत लहान संख्या शोधा. त्यानंतर उरलेल्या संख्यांमधील पुढची लहान संख्या निवडा. योग्य क्रम असा आहे: ${sorted.map(class4Digits).join(' → ')}.';
    case 'match':
      prompt = 'प्रत्येक संख्येची तेवढेच ठिपके असलेल्या गटाशी जोडी जुळवा.';
      explanation =
          'प्रत्येक गटातील ठिपके एकदाच मोजा. १ ची जोडी ● बरोबर, २ ची जोडी ●● बरोबर आणि ३ ची जोडी ●●● बरोबर जुळते.';
    case 'clock':
      prompt =
          'दिलेली वेळ दाखवण्यासाठी घड्याळाचा लहान तासकाटा योग्य अंकावर न्या.';
    case 'coins':
      prompt = 'खाली दिलेली रक्कम पाहा. तेवढी रक्कम होईल अशी नाणी निवडा.';
    case 'colour':
      prompt =
          'दिलेला अपूर्णांक दाखवण्यासाठी पूर्ण आकाराचे समान भाग वापरा आणि योग्य तेवढे भाग रंगवा.';
    case 'graph':
      prompt =
          'गायी आणि शेळ्यांची संख्या पाहा. ही संख्या बरोबर दाखवणारा आलेख निवडा.';
    case 'model':
      if (topic == 'count') prompt = '$a वस्तू असलेला गट चित्रांतून शोधा.';
    case 'numberline':
      if (topic == 'count') prompt = 'संख्यारेषेवर $a ही संख्या शोधा.';
  }
  return Question(
    class4Wording(q.prompt, prompt),
    class4Wording(q.explanation, explanation),
    q.answer,
    q.a,
    q.b,
    q.options,
    q.type,
    q.icon,
    metadata: q.metadata,
  );
}

/// Small, context-specific help cards for the existing Class 4 topic tools.
Words class4LearningHelp(String topic, String field, Words original) {
  final normalized = field == 'commonMistake' ? 'mistake' : field;
  final fields = _class4Help[topic];
  final wording = fields?[normalized];
  return wording == null ? original : class4Wording(original, wording);
}

Words class4LegacyStory(String topic, Words original) {
  final wording = _class4Stories[topic];
  return wording == null ? original : class4Wording(original, wording);
}

