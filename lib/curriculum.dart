// Original paraphrases; not official outcome identifiers.
class CurriculumOutcome {
  final String id, topic, prerequisite, vocabulary, source, review;
  final int grade;
  final Words _objective, _definition, _hint, _commonMistake;
  const CurriculumOutcome(
    this.id,
    this.grade,
    this.topic,
    this.prerequisite,
    this.vocabulary,
    this.source,
    this.review,
    this._objective,
    this._definition,
    this._hint,
    this._commonMistake,
  );
  Words _classWording(String field, Words text) => grade == 4
      ? class4LearningHelp(topic, field, text)
      : primaryLearningHelp(grade, topic, field, text);
  Words get objective => _classWording(
    'objective',
    _objective.identified(
      '$id.objective',
      glossaryTerms: glossaryTermsFor(topic),
    ),
  );
  Words get definition => _classWording(
    'definition',
    _definition.identified(
      '$id.definition',
      glossaryTerms: glossaryTermsFor(topic),
    ),
  );
  Words get hint => _classWording(
    'hint',
    _hint.identified('$id.hint', glossaryTerms: glossaryTermsFor(topic)),
  );
  Words get commonMistake => _classWording(
    'commonMistake',
    _commonMistake.identified(
      '$id.commonMistake',
      glossaryTerms: glossaryTermsFor(topic),
    ),
  );
  Words get vocabularyText => _classWording(
    'vocabulary',
    Words(
      vocabulary.split(' / ').first,
      vocabulary.split(' / ').last,
    ).identified('$id.vocabulary', glossaryTerms: glossaryTermsFor(topic)),
  );
}

