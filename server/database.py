"""Small DB-API adapter. PostgreSQL is required in production; SQLite is dev-only."""
import contextlib
from urllib.parse import urlsplit, urlunsplit, parse_qsl, urlencode
import sqlite3
import re
import time
from pathlib import Path


def postgres_url(url):
    """Use the packaged public CA bundle while retaining hostname verification."""
    parts = urlsplit(url)
    query = dict(parse_qsl(parts.query))
    if query.get('sslrootcert') == 'system':
        query['sslrootcert'] = str(Path(__file__).with_name('ca-certificates.crt').resolve())
    return urlunsplit(parts._replace(query=urlencode(query)))


class Database:
    def __init__(self, path, url='', schema=''):
        self.postgres = bool(url)
        if self.postgres:
            import psycopg
            from psycopg.rows import dict_row
            self.raw = psycopg.connect(postgres_url(url), row_factory=dict_row, connect_timeout=8)
            if schema:
                if not re.fullmatch(r'[a-z][a-z0-9_]{0,62}', schema):
                    self.raw.close()
                    raise ValueError('Invalid database schema')
                from psycopg import sql
                self.raw.execute(sql.SQL('SET search_path TO {}').format(sql.Identifier(schema)))
        else:
            self.raw = sqlite3.connect(path, timeout=20)
            self.raw.row_factory = sqlite3.Row
            self.raw.execute('PRAGMA foreign_keys=ON')
            self.raw.execute('PRAGMA busy_timeout=20000')

    def execute(self, sql, args=()):
        if self.postgres and sql.lstrip().upper().startswith(('CREATE', 'ALTER')):
            sql = re.sub(r'\bREAL\b', 'DOUBLE PRECISION', sql)
        return self.raw.execute(sql.replace('?', '%s') if self.postgres else sql, args)

    def executescript(self, sql):
        for statement in sql.split(';'):
            if statement.strip():
                self.execute(statement)

    def commit(self):
        self.raw.commit()

    def rollback(self):
        self.raw.rollback()

    def close(self):
        self.raw.close()


@contextlib.contextmanager
def connect(path, url='', schema=''):
    db = Database(path, url, schema)
    try:
        yield db
        db.commit()
    except Exception:
        db.rollback()
        raise
    finally:
        db.close()


def migrate(db):
    if db.postgres:
        db.execute('SELECT pg_advisory_xact_lock(?,?)', (101, 20261101))
    db.execute('CREATE TABLE IF NOT EXISTS schema_migrations(version INTEGER PRIMARY KEY,applied_at REAL NOT NULL)')
    versions = {row['version'] for row in db.execute('SELECT version FROM schema_migrations')}
    if 1 not in versions:
        script = Path(__file__).with_name('migrations').joinpath('001_foundation.sql').read_text()
        if db.postgres:
            script = script.replace('id INTEGER PRIMARY KEY,at', 'id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,at')
        db.executescript(script)
        db.execute('INSERT INTO schema_migrations VALUES(?,?)', (1, time.time()))
    if 2 not in versions:
        additions = {
            'users': {'status': "TEXT NOT NULL DEFAULT 'active'", 'must_change_password': 'INTEGER NOT NULL DEFAULT 0', 'last_login': 'REAL', 'created_at': 'REAL NOT NULL DEFAULT 0'},
            'sessions': {'device_id': 'TEXT', 'install_id': "TEXT NOT NULL DEFAULT ''", 'family_id': "TEXT NOT NULL DEFAULT ''", 'created_at': 'REAL NOT NULL DEFAULT 0'},
            'classrooms': {'school_id': 'TEXT', 'section': "TEXT NOT NULL DEFAULT ''", 'status': "TEXT NOT NULL DEFAULT 'active'", 'created_at': 'REAL NOT NULL DEFAULT 0'},
            'devices': {'teacher_id': 'TEXT', 'current_mode': "TEXT NOT NULL DEFAULT 'idle'", 'current_grade': 'INTEGER NOT NULL DEFAULT 1', 'chapter_id': "TEXT NOT NULL DEFAULT ''", 'last_interaction': 'REAL', 'network_state': "TEXT NOT NULL DEFAULT 'unknown'", 'error_count': 'INTEGER NOT NULL DEFAULT 0', 'session_count': 'INTEGER NOT NULL DEFAULT 0', 'created_at': 'REAL NOT NULL DEFAULT 0', 'last_login': 'REAL', 'last_error': "TEXT NOT NULL DEFAULT ''", 'reauth_required': 'INTEGER NOT NULL DEFAULT 0'},
        }
        for table, columns in additions.items():
            if db.postgres:
                present = {row['column_name'] for row in db.execute("SELECT column_name FROM information_schema.columns WHERE table_schema=current_schema() AND table_name=?", (table,))}
            else:
                present = {row['name'] for row in db.execute(f'PRAGMA table_info({table})')}
            for name, definition in columns.items():
                if name not in present:
                    db.execute(f'ALTER TABLE {table} ADD COLUMN {name} {definition}')
        db.executescript(Path(__file__).with_name('migrations').joinpath('002_monitoring.sql').read_text())
        db.execute("UPDATE users SET role='super_admin' WHERE role='admin'")
        for role in ('super_admin', 'school_admin', 'teacher', 'viewer'):
            db.execute('INSERT INTO roles(id) VALUES(?) ON CONFLICT DO NOTHING', (role,))
        # Preserve classrooms and assignments from the previous local database.
        for room in list(db.execute('SELECT * FROM classrooms')):
            sid = 'migrated-school-' + __import__('hashlib').sha256(room['school'].encode()).hexdigest()[:20]
            db.execute('INSERT INTO schools(id,name,code,created_at) VALUES(?,?,?,?) ON CONFLICT DO NOTHING', (sid, room['school'], sid, time.time()))
            db.execute('UPDATE classrooms SET school_id=?,created_at=? WHERE id=?', (sid, time.time(), room['id']))
            if room['teacher_id']:
                db.execute('INSERT INTO classroom_assignments(classroom_id,user_id) VALUES(?,?) ON CONFLICT DO NOTHING', (room['id'], room['teacher_id']))
                db.execute('INSERT INTO user_schools(user_id,school_id) VALUES(?,?) ON CONFLICT DO NOTHING', (room['teacher_id'], sid))
        for teacher in db.execute("SELECT id FROM users WHERE role='teacher'"):
            db.execute('INSERT INTO teachers VALUES(?,?) ON CONFLICT DO NOTHING', (teacher['id'], time.time()))
        db.execute('UPDATE devices SET created_at=? WHERE created_at=0', (time.time(),))
        # Legacy sessions had no device binding or rotating refresh family.
        db.execute('DELETE FROM sessions')
        db.execute('UPDATE users SET must_change_password=1')
        db.execute('INSERT INTO schema_migrations VALUES(?,?)', (2, time.time()))

    if 3 not in versions:
        if db.postgres:
            # Epoch seconds cannot use PostgreSQL float4: at contemporary dates
            # a heartbeat can lose over a minute of precision.
            tables = {'schema_migrations','sessions','users','classrooms','devices','audit','schools','teachers','device_sessions','refresh_tokens','password_reset_tokens','heartbeats','activity_events','usage_daily','app_versions','error_events','audit_logs','alerts','login_attempts'}
            columns = list(db.execute("SELECT table_name,column_name FROM information_schema.columns WHERE table_schema=current_schema() AND data_type='real'"))
            for column in columns:
                if column['table_name'] in tables:
                    table = column['table_name'].replace('"', '""')
                    name = column['column_name'].replace('"', '""')
                    db.execute(f'ALTER TABLE "{table}" ALTER COLUMN "{name}" TYPE DOUBLE PRECISION')
        db.execute('INSERT INTO schema_migrations VALUES(?,?)', (3, time.time()))

    if 4 not in versions:
        if db.postgres:
            present = {r['column_name'] for r in db.execute("SELECT column_name FROM information_schema.columns WHERE table_schema=current_schema() AND table_name='devices'")}
        else:
            present = {r['name'] for r in db.execute('PRAGMA table_info(devices)')}
        if 'connection_state' not in present:
            db.execute("ALTER TABLE devices ADD COLUMN connection_state TEXT NOT NULL DEFAULT 'never_connected'")
        db.execute('INSERT INTO schema_migrations VALUES(?,?)', (4, time.time()))

    if 5 not in versions:
        if db.postgres:
            present = {r['column_name'] for r in db.execute("SELECT column_name FROM information_schema.columns WHERE table_schema=current_schema() AND table_name='devices'")}
        else:
            present = {r['name'] for r in db.execute('PRAGMA table_info(devices)')}
        if 'version_updated_at' not in present:
            db.execute('ALTER TABLE devices ADD COLUMN version_updated_at REAL')
        db.execute('INSERT INTO schema_migrations VALUES(?,?)', (5, time.time()))

    if 6 not in versions:
        db.executescript(Path(__file__).with_name('migrations').joinpath('006_school_logins.sql').read_text())
        db.execute('INSERT INTO schema_migrations VALUES(?,?)', (6, time.time()))
